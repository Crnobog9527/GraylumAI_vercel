// ARCH-FIX H1: the current full definition of every public function (Owner 2026-10-26: all of them), kept as
// files in packages/db/functions/<group>/<function name>.sql. The files are exported from the
// database built from repository files (run-db-baseline-replay.mjs), never copied from staging, and
// CI requires them to equal that build. A PR that changes one of these functions regenerates them
// with the same command as the built fingerprint: --write-built (see packages/db/functions/README.md).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

export const FUNCTIONS_DIR = 'packages/db/functions';
// group directory -> function-name pattern (anchored, POSIX regex on pg_proc.proname). The first matching group wins;
// a function no pattern matches goes to OTHER, so every public function has a file.
export const OTHER = 'other';
export const GROUPS = {
  billing: '^(bill2_|atomic_|credit_)',
  runtime: '^runtime_',
  erasure: '^(account_erasure_|content_erasure_)',
  pay: '^pay_',
  publish: '^publish_',
  opc: '^opc_',
  fusion: '^fusion_',
  library: '^library_',
  report: '^report_',
  research: '^research_',
  voice: '^voice_',
  // CORE-PATH-V2: the per-turn core functions (turn_open, turn_call_*, turn_close, turn_settle_credits, turn_tombstones).
  turn: '^turn_',
};

const groupOf = () => `CASE ${Object.entries(GROUPS).map(([key, pattern]) => `WHEN p.proname ~ '${pattern}' THEN '${key}'`).join(' ')}
  ELSE '${OTHER}' END`;

// Functions that belong to an extension are the extension's, not the repository's, and are left out.
export const snapshotSql = () => `SELECT coalesce(jsonb_agg(jsonb_build_object('group', f.grp, 'name', f.proname,
  'signature', f.signature, 'def', f.def) ORDER BY f.grp, f.proname, f.signature), '[]')
FROM (SELECT ${groupOf()} AS grp, p.proname, p.oid::regprocedure::text AS signature, pg_get_functiondef(p.oid) AS def
  FROM pg_proc p
  WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e')) f;`;

// rows from snapshotSql() -> { 'billing/bill2_x.sql': text }; overloads share one file, ordered by signature.
export function renderSnapshots(rows) {
  const files = {};
  for (const row of rows) {
    const path = `${row.group}/${row.name}.sql`;
    const header = `-- ${row.signature}\n`;
    files[path] = `${files[path] ?? ''}${header}${row.def.trimEnd()};\n\n`;
  }
  const banner = '-- Generated by packages/db/tests/run-db-baseline-replay.mjs --write-built from the database built '
    + 'from repository files.\n-- Do not edit by hand; see packages/db/functions/README.md.\n\n';
  return Object.fromEntries(Object.entries(files).map(([path, text]) => [path, banner + text.trimEnd() + '\n']));
}

const existing = (root) => {
  const base = resolve(root, FUNCTIONS_DIR);
  const found = {};
  if (!existsSync(base)) return found;
  for (const group of readdirSync(base)) {
    if (!statSync(resolve(base, group)).isDirectory()) continue;
    for (const file of readdirSync(resolve(base, group)).filter(name => name.endsWith('.sql'))) {
      found[`${group}/${file}`] = readFileSync(resolve(base, group, file), 'utf8');
    }
  }
  return found;
};

// Differences between the build and the committed files (empty when they match).
export function compareSnapshots(root, files) {
  const committed = existing(root);
  const problems = [];
  for (const path of Object.keys(files).sort()) {
    if (!(path in committed)) problems.push(`function file missing from the repository: ${path}`);
    else if (committed[path] !== files[path]) problems.push(`function file differs from the build: ${path}`);
  }
  for (const path of Object.keys(committed).sort()) {
    if (!(path in files)) problems.push(`function file without a function in the build: ${path}`);
  }
  return problems;
}

export function writeSnapshots(root, files) {
  for (const path of Object.keys(existing(root))) if (!(path in files)) rmSync(resolve(root, FUNCTIONS_DIR, path));
  for (const [path, text] of Object.entries(files)) {
    const target = resolve(root, FUNCTIONS_DIR, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
}
