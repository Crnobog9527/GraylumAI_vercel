// REVIEW-COACH RC-0: turns the simulated dataset into one SQL transaction for a given user and brands. The same SQL
// is what the local suite runs and what an approved staging load would run, so the local suite tests the real thing.
// Only existing tables and the existing account-add RPC are used; nothing calls Post for Me or TikHub:
// connections are created with automatic tracking off, which the daily refresh claims (Post for Me and TikHub) skip.
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
/** Every simulated connection carries this display prefix; removal only ever touches rows with it. */
export const SIM_HINT = 'SIM-';

function dollarQuote(json) {
  const text = JSON.stringify(json);
  if (text.includes('$sim$')) throw new Error('SIM_PAYLOAD_DELIMITER');
  return `$sim$${text}$sim$::jsonb`;
}

/** Which generated dataset a connection holds; stored in its display hint so a different load can be refused. */
export function datasetTag(dataset) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(dataset.asOf) || !Number.isSafeInteger(dataset.seed)) throw new Error('SIM_DATASET_INVALID');
  return `${dataset.asOf} s${dataset.seed}`;
}

/** Rows one account loads into social_connections / social_posts / social_metric_snapshots. */
export function loadable(account, tag = '') {
  const posts = account.posts.filter(p => p.visibility !== 'not_imported');
  const connectedOn = Object.fromEntries(account.connections.map(c => [c.platform, c.connectedOn]));
  return {
    connections: account.connections.map(c => ({ platform: c.platform, source: c.source, connected_on: c.connectedOn,
      hint: `${SIM_HINT}${account.key} ${c.platform} ${tag}`.trim() })),
    posts: posts.map(p => ({ key: p.key, platform: p.platform, source: p.source, platform_post_id: p.platformPostId,
      posted_at: p.postedAt, posted_at_source: p.postedAtSource, title: p.title,
      created_at: p.visibility === 'daily' ? p.postedAt : `${connectedOn[p.platform]}T12:00:00Z` })),
    snapshots: account.snapshots.map(s => ({ platform: s.platform, post_key: s.postKey, captured_on: s.capturedOn,
      metrics: s.metrics, missing: s.missingFields })),
    diagnostics: (account.diagnostics ?? []).map(x => ({ platform: x.platform,
      platform_post_id: account.posts.find(p => p.key === x.postKey).platformPostId, source: x.source, rates: x.rates,
      opening_text: x.openingText, video_seconds: x.videoSeconds, drop_second: x.dropSecond, captured_on: x.capturedOn })),
  };
}

/**
 * @param dataset generateDataset() output
 * @param actorId the user that receives the data
 * @param businesses { A: businessId, ... } — each simulated account goes into one existing, positioned brand of the user;
 *   accounts not listed are skipped. A brand's platform account is reused when it exists, otherwise created with the
 *   product's own publish_monitor_account_add. A platform account that already has a live connection stops the load.
 *   Loading the same dataset again adds nothing; simulated data from another dataset (other asOf or seed) in the
 *   brand stops the load too, so rows of two generations never mix: remove it first.
 */
export function seedSql(dataset, actorId, businesses) {
  if (!UUID.test(actorId)) throw new Error('SIM_ACTOR_INVALID');
  const parts = [`-- Generated by packages/db/tests/publish-monitor-coach/seed.mjs: simulated data, asOf ${dataset.asOf}.`,
    'BEGIN;'];
  for (const account of dataset.accounts) {
    const business = businesses[account.key];
    if (business === undefined) continue;
    if (!UUID.test(business)) throw new Error('SIM_BUSINESS_INVALID');
    parts.push(accountSql(account, actorId, business, datasetTag(dataset)));
  }
  parts.push('COMMIT;');
  return parts.join('\n');
}

function accountSql(account, actorId, businessId, tag) {
  const short = actorId.slice(0, 8);
  return `DO $do$
DECLARE a uuid:='${actorId}';b uuid:='${businessId}';d jsonb:=${dollarQuote(loadable(account, tag))};
 c jsonb;acct uuid;conn uuid;ids jsonb:='{}';
BEGIN
 IF EXISTS(SELECT 1 FROM social_connections WHERE actor_id=a AND business_id=b AND display_hint LIKE '${SIM_HINT}%'
  AND display_hint NOT IN (SELECT x->>'hint' FROM jsonb_array_elements(d->'connections') x)) THEN
  RAISE EXCEPTION 'SIM_OTHER_DATASET_LOADED: remove the simulated data of this user first (seed.mjs remove)';
 END IF;
 FOR c IN SELECT * FROM jsonb_array_elements(d->'connections') LOOP
  SELECT project_id INTO acct FROM opc_accounts WHERE actor_id=a AND business_id=b AND platform=c->>'platform'
   AND erased_at IS NULL ORDER BY project_id LIMIT 1;
  IF acct IS NULL THEN
   acct:=(publish_monitor_account_add(a,b,c->>'platform','sim-${account.key.toLowerCase()}-'||(c->>'platform'))->>'accountProjectId')::uuid;
  END IF;
  SELECT id INTO conn FROM social_connections WHERE account_project_id=acct AND actor_id=a
   AND status IN ('connected','reauth_required','quarantined');
  IF conn IS NOT NULL AND NOT EXISTS(SELECT 1 FROM social_connections WHERE id=conn AND display_hint LIKE '${SIM_HINT}%') THEN
   RAISE EXCEPTION 'SIM_ACCOUNT_ALREADY_CONNECTED: %',c->>'platform';
  END IF;
  IF conn IS NULL THEN
   INSERT INTO social_connections(actor_id,business_id,account_project_id,role,source,platform,provider_account_id,profile_ref,
    display_hint,status,consent_read,consent_auto_track,last_success_at,created_at)
   VALUES(a,b,acct,'own',c->>'source',c->>'platform',
    CASE WHEN c->>'source'='postforme' THEN 'sim_${short}_${account.key.toLowerCase()}_'||(c->>'platform') END,
    CASE WHEN c->>'source'='tikhub' THEN 'sim:${account.key}:'||(c->>'platform') END,
    c->>'hint','connected',true,false,now(),(c->>'connected_on')::date+time '12:00') RETURNING id INTO conn;
  END IF;
  ids:=ids||jsonb_build_object(c->>'platform',conn);
 END LOOP;
 INSERT INTO social_posts(actor_id,connection_id,source,platform_post_id,posted_at,posted_at_source,title_excerpt,created_at)
 SELECT a,(ids->>p.platform)::uuid,p.source,p.platform_post_id,p.posted_at,p.posted_at_source,p.title,p.created_at
 FROM jsonb_to_recordset(d->'posts') p(platform text,source text,platform_post_id text,posted_at timestamptz,
  posted_at_source text,title text,created_at timestamptz)
 ON CONFLICT(connection_id,source,platform_post_id) DO NOTHING;
 INSERT INTO social_metric_snapshots(actor_id,connection_id,post_id,captured_on,captured_at,source,metrics,missing_fields)
 SELECT a,(ids->>s.platform)::uuid,sp.id,s.captured_on,s.captured_on+time '06:00',
  (SELECT source FROM social_connections WHERE id=(ids->>s.platform)::uuid),s.metrics,
  ARRAY(SELECT jsonb_array_elements_text(s.missing))
 FROM jsonb_to_recordset(d->'snapshots') s(platform text,post_key text,captured_on date,metrics jsonb,missing jsonb)
 LEFT JOIN jsonb_to_recordset(d->'posts') p(key text,platform_post_id text) ON p.key=s.post_key
 LEFT JOIN social_posts sp ON sp.connection_id=(ids->>s.platform)::uuid AND sp.platform_post_id=p.platform_post_id
 WHERE s.post_key IS NULL OR sp.id IS NOT NULL
 ON CONFLICT DO NOTHING;
 -- Back-office rate diagnostics only where migration 0407 created their table.
 IF to_regclass('public.social_post_diagnostics') IS NOT NULL THEN
  INSERT INTO social_post_diagnostics(actor_id,business_id,post_id,platform,source,rates,opening_text,video_seconds,drop_second,
   captured_on,confirmed_at)
  SELECT a,b,sp.id,x.platform,x.source,x.rates,x.opening_text,x.video_seconds,x.drop_second,x.captured_on,now()
  FROM jsonb_to_recordset(d->'diagnostics') x(platform text,platform_post_id text,source text,rates jsonb,opening_text text,
   video_seconds integer,drop_second integer,captured_on date)
  JOIN social_posts sp ON sp.connection_id=(ids->>x.platform)::uuid AND sp.platform_post_id=x.platform_post_id
  ON CONFLICT DO NOTHING;
 END IF;
END $do$;`;
}

/** Deletes only the simulated rows of one user (snapshots, posts, connections marked SIM-); brand accounts stay. */
export function removeSql(actorId) {
  if (!UUID.test(actorId)) throw new Error('SIM_ACTOR_INVALID');
  return `-- Removes simulated review-coach data for one user (connections whose display hint starts with ${SIM_HINT}).
BEGIN;
CREATE TEMP TABLE sim_conn ON COMMIT DROP AS SELECT id FROM social_connections
 WHERE actor_id='${actorId}' AND display_hint LIKE '${SIM_HINT}%';
DELETE FROM social_metric_snapshots WHERE connection_id IN (SELECT id FROM sim_conn);
DELETE FROM social_posts WHERE connection_id IN (SELECT id FROM sim_conn);
DELETE FROM social_connections WHERE id IN (SELECT id FROM sim_conn);
COMMIT;`;
}
