// CONTENT-CONVERSATION-DRIVEN A2 (migration 0276): derived-content source checkpoint, availability, D7, saves.
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {rpc,fixture,outcome,call,evidence} from '../erasure-b2a/cases.mjs';
import {erase} from '../content-erasure/cases.mjs';

const def=async(db,sig)=>(await db.query('SELECT pg_get_functiondef($1::regprocedure) d',[sig])).rows[0].d;
const one=async(db,sql,args)=>(await db.query(sql,args)).rows[0];
const refusedWith=async(promise,pattern)=>assert.rejects(promise,error=>pattern.test(error.message));

// One video work item with the D7 fixture's final script v1 (no generating execution) and its topic session.
async function topic(db){
 const f=await fixture(db);
 await db.query('UPDATE profiles SET credits=1000 WHERE id=$1',[f.actor]);
 const art=(await db.query('SELECT a2_test.link(d7_test.artifacts($1)) v',[f.actor])).rows[0].v;
 const scope=(await one(db,'SELECT scope FROM runtime_sessions WHERE id=$1',[art.session])).scope;
 return {...f,art,scope};
}
// An admitted, running execution of the topic session (the executor's state when it reaches checkpoint_source).
async function running(db,t,payload={},session=t.art.session,scope=t.scope){
 const run=await rpc(db,'bill2_prepare',t.actor,randomUUID(),{...t.payload,scope}),id=randomUUID();
 await db.query(`INSERT INTO runtime_executions(id,actor_id,session_id,request_id,payload,history_revision,state,billing_run_id)
  VALUES($1,$2,$3,$4,$5,0,'running',$6)`,[id,t.actor,session,randomUUID(),payload,run.id]);
 await db.query('UPDATE bill2_runs SET session_ref=$2 WHERE id=$1',[run.id,session]);
 await db.query('UPDATE runtime_sessions SET active_execution=$2 WHERE id=$1',[session,id]);
 return {id,run:run.id};
}
async function complete(db,t,x,body){
 const c=await call(db,{...t,run:x.run});
 await rpc(db,'bill2_record',t.actor,x.run,c.id,evidence(c));
 await rpc(db,'bill2_close',t.actor,x.run,'delivered',outcome);
 await rpc(db,'bill2_finalize',t.actor,x.run);
 await db.query("UPDATE runtime_executions SET state='completed',result=$2 WHERE id=$1",[x.id,{...outcome,body}]);
 await db.query('UPDATE runtime_sessions SET active_execution=NULL WHERE id=$1 AND active_execution=$2',[t.art.session,x.id]);
}
const activate=(db,t,x)=>db.query('UPDATE runtime_sessions SET active_execution=$2 WHERE id=$1',[t.art.session,x.id]);
const checkpoint=(db,t,x,kind)=>rpc(db,'runtime_execution',t.actor,x.id,'checkpoint_source',{kind});
const injected=async(db,x)=>(await one(db,'SELECT injected_source v FROM runtime_executions WHERE id=$1',[x.id])).v;
const save=(db,t,kind,x,expected,source=null,request=randomUUID())=>
 rpc(db,'opc_content_from_execution',t.actor,t.art.workItem,request,expected,kind,'final',x.id,source);
const available=async(db,x)=>(await one(db,'SELECT runtime_history_available($1) v',[x.id])).v;
const batch=async(db,x)=>(await one(db,'SELECT available v FROM runtime_history_availability(ARRAY[$1::uuid])',[x.id])).v;
// A final script generated by its own completed execution (so revoking that execution revokes the script).
async function generatedScript(db,t,expected,body){
 const x=await running(db,t);await complete(db,t,x,body);
 return {x,content:await save(db,t,'script',x,expected)};
}

export async function runCases(db,report){
 // Patched functions keep their D7 guards and carry this migration's markers.
 for(const [sig,markers] of [
  ['opc_content_from_execution(uuid,uuid,uuid,bigint,text,text,uuid,uuid)',[/-- D7 read boundary/,/-- A2 derived source/]],
  ['runtime_execution(uuid,uuid,text,jsonb)',[/-- A2 checkpoint_source/]],
  ['runtime_direct_billing_allowed(uuid,jsonb,uuid)',[/-- D7 original execution/,/-- A2 injected source/]],
  ['content_erasure_scope(uuid,text,uuid)',[/-- A2 injected source/]]]){
  const d=await def(db,sig);for(const marker of markers)assert.match(d,marker,sig);
 }
 for(const role of ['anon','authenticated'])
  for(const sig of ['opc_content_source_current(uuid,uuid,text)','runtime_source_checkpoint(uuid,runtime_sessions,runtime_executions,bill2_runs,jsonb)',
   'opc_content_source_pick(uuid,uuid,text,uuid,boolean)'])
   assert.equal((await one(db,'SELECT has_function_privilege($1,$2,\'EXECUTE\') v',[role,sig])).v,false,role+' '+sig);
 report.checks.push('patched functions keep D7 guards; new functions are not callable by anon or authenticated');

 // Script source: chosen in the database, recorded with the read, reused on replay and after a newer final script.
 const t=await topic(db);
 const x=await running(db,t);
 const read=await checkpoint(db,t,x,'script');
 assert.deepEqual(read,{status:'injected',contentId:t.art.content,kind:'script',version:1,body:'D7_INDEPENDENT_SAVED_BODY'});
 assert.deepEqual(await injected(db,x),{items:[{contentId:t.art.content,kind:'script'}]});
 const v2=(await generatedScript(db,t,1,'A2_SCRIPT_V2')).content;
 await activate(db,t,x);// x resumes (recovery) after a newer final script was saved elsewhere
 assert.deepEqual(await checkpoint(db,t,x,'script'),read,'replay reuses the recorded version, never the newer one');
 await refusedWith(checkpoint(db,t,x,'storyboard'),/RUNTIME_CONTENT_SOURCE_CONFLICT/);
 await refusedWith(rpc(db,'runtime_execution',t.actor,x.id,'checkpoint_source',{kind:'editing'}),/RUNTIME_CONTENT_SOURCE_DENIED/);
 await refusedWith(rpc(db,'runtime_execution',t.actor,x.id,'checkpoint_source',{kind:'script',extra:1}),/RUNTIME_CONTENT_SOURCE_DENIED/);
 const other=await fixture(db);
 await refusedWith(rpc(db,'runtime_execution',other.actor,x.id,'checkpoint_source',{kind:'script'}),/RUNTIME_EXECUTION_DENIED/);
 const fresh=await running(db,t);
 assert.equal((await checkpoint(db,t,fresh,'script')).contentId,v2.id,'a first read takes the latest available final script');
 await complete(db,t,fresh,'A2_FRESH');
 report.checks.push('checkpoint_source reads and records the latest final script; replays keep the recorded version');

 // Directly chosen Skill: admission reads the version without its body; the checkpoint injects exactly that one.
 const current=await rpc(db,'opc_content_source_current',t.actor,t.art.session,'script');
 assert.deepEqual(current,{status:'ready',contentId:v2.id,kind:'script',bytes:Buffer.byteLength('A2_SCRIPT_V2')});
 const frozen=await running(db,t,{sourceContent:{contentId:t.art.content,kind:'script'}});
 assert.equal((await checkpoint(db,t,frozen,'script')).contentId,t.art.content,'the admission-frozen version is injected');
 await refusedWith(checkpoint(db,t,frozen,'storyboard'),/RUNTIME_CONTENT_SOURCE_CONFLICT/);
 await complete(db,t,frozen,'A2_FROZEN');
 report.checks.push('a directly chosen Skill reads the version frozen at admission; admission never returns the body');

 // Storyboard save takes the injected script as its source; the browser cannot substitute another one.
 await activate(db,t,x);await complete(db,t,x,'A2_STORYBOARD_FROM_V1');
 const plain=await running(db,t);await complete(db,t,plain,'A2_PLAIN_REPLY');
 await refusedWith(save(db,t,'storyboard',plain,0),/OPC_CONTENT_SOURCE/);
 await refusedWith(save(db,t,'storyboard',x,0,v2.id),/OPC_CONTENT_SOURCE/);
 const request=randomUUID();
 const board=await save(db,t,'storyboard',x,0,null,request);
 assert.equal((await one(db,'SELECT source_content_id v FROM opc_content_versions WHERE id=$1',[board.id])).v,t.art.content,
  'a storyboard from script v1 is saved as based on v1 although v2 is current');
 assert.deepEqual(await save(db,t,'storyboard',x,0,null,request),board,'replay returns the same version');
 report.checks.push('storyboard saves take the injected script; missing or substituted sources are refused; replay is stable');

 // Editing advice reads only a storyboard of the current final script.
 const stale=await running(db,t);
 assert.deepEqual(await checkpoint(db,t,stale,'storyboard'),{status:'refused',code:'RUNTIME_CONTENT_SOURCE_STALE'});
 assert.equal(await injected(db,stale),null,'a refusal records nothing');
 assert.deepEqual(await rpc(db,'opc_content_source_current',t.actor,t.art.session,'storyboard'),
  {status:'refused',code:'RUNTIME_CONTENT_SOURCE_STALE'});
 await complete(db,t,stale,'A2_STALE');
 const y=await running(db,t);
 assert.equal((await checkpoint(db,t,y,'script')).contentId,v2.id);await complete(db,t,y,'A2_STORYBOARD_FROM_V2');
 const board2=await save(db,t,'storyboard',y,1);
 const z=await running(db,t);
 assert.deepEqual(await checkpoint(db,t,z,'storyboard'),{status:'injected',contentId:board2.id,kind:'storyboard',version:2,
  body:'A2_STORYBOARD_FROM_V2'});
 await complete(db,t,z,'A2_EDITING');
 const editing=await save(db,t,'editing',z,0);
 assert.equal((await one(db,'SELECT source_content_id v FROM opc_content_versions WHERE id=$1',[editing.id])).v,board2.id);
 await refusedWith(save(db,t,'editing',y,1),/OPC_CONTENT_SOURCE/);
 report.checks.push('editing reads only a storyboard of the current final script and saves it as its source');

 // Not a topic window, or nothing saved yet.
 const empty=await topic(db);
 await db.query('DELETE FROM opc_content_versions WHERE id=$1',[empty.art.content]).catch(()=>{});
 // The B2a fixture's running execution lives in a positioning draft session, not a topic window.
 const none={id:(await one(db,'SELECT b2a_test.bind($1) v',[empty])).v};
 await db.query("UPDATE runtime_executions SET state='running' WHERE id=$1",[none.id]);
 assert.deepEqual(await rpc(db,'runtime_execution',empty.actor,none.id,'checkpoint_source',{kind:'script'}),{status:'none'});
 assert.equal(await injected(db,none),null);
 const missing=await running(db,empty);
 assert.deepEqual(await rpc(db,'runtime_execution',empty.actor,missing.id,'checkpoint_source',{kind:'storyboard'}),
  {status:'refused',code:'RUNTIME_CONTENT_SOURCE_MISSING'});
 report.checks.push('outside a topic window nothing is injected; a topic without the source is refused');

 // Availability: revoking the injected script's generating execution hides every turn that read it (single and batch).
 const u=await topic(db);
 const gen=await generatedScript(db,u,1,'A2_GENERATED_SCRIPT');
 const derived=await running(db,u);
 assert.equal((await checkpoint(db,u,derived,'script')).contentId,gen.content.id);
 await complete(db,u,derived,'A2_DERIVED');
 const later=await running(db,u);await complete(db,u,later,'A2_LATER');
 await db.query('INSERT INTO runtime_history_dependencies(execution_id,dependency_id) VALUES($1,$2)',[later.id,derived.id]);
 assert.equal(await available(db,derived),true);assert.equal(await batch(db,derived),true);
 await db.query("UPDATE runtime_executions SET unavailable_reason='output_truncated' WHERE id=$1",[gen.x.id]);
 for(const e of [derived,later]){
  assert.equal(await available(db,e),false,'single history check');assert.equal(await batch(db,e),false,'batch history check');
 }
 await refusedWith(save(db,u,'storyboard',derived,0),/OPC_CONTENT_DENIED|OPC_CONTENT_SOURCE/);
 report.checks.push('revoking an injected source makes the reading turn and its descendants unavailable (single and batch)');

 // D7: deleting the injected script erases the turn that read it; deleting another family leaves it.
 const w=await topic(db);
 const readTurn=await running(db,w);await checkpoint(db,w,readTurn,'script');await complete(db,w,readTurn,'A2_READ_TURN');
 const scope=await rpc(db,'content_erasure_scope',w.actor,'content',w.art.content);
 assert.ok(JSON.stringify(scope).includes(readTurn.id),'the injecting execution is in the deletion closure');
 await erase(db,w,'content',w.art.content);
 const gone=await one(db,'SELECT payload,result,content_deleted_at FROM runtime_executions WHERE id=$1',[readTurn.id]);
 assert.ok(gone.content_deleted_at,'the injecting execution is erased');
 assert.doesNotMatch(JSON.stringify(gone),/A2_READ_TURN|D7_INDEPENDENT_SAVED_BODY/);
 report.checks.push('D7 content deletion erases every execution that injected that content');

 return {topic,running,complete,checkpoint};
}
